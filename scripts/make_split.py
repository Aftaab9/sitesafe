"""Step 2: carve a fixed, seeded, stratified 100-image TEST split out of train.

Construction-PPE ships only train (800) and val (200). Reporting final numbers on val
would be optimistic because val is used for model selection, so:

    train (700)  -> fitting
    val   (200)  -> model selection, thresholds, calibration
    test  (100)  -> final numbers only, never trained on

Stratification: a light iterative scheme. At every step the class that is furthest below
its proportional target is topped up with a random image that contains it. This guarantees
every class (in particular every no_* class and forklift) is present in the test split.

Outputs data/splits/{train,val,test}.txt (repo-relative image paths, committed so the split
is reproducible byte for byte) and data/splits/ppe.yaml (absolute paths, generated).
"""
from __future__ import annotations

import json
import random
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from sitesafe.classes import CLASS_NAMES  # noqa: E402
from sitesafe.paths import DATASET, ROOT, SEED, SPLITS  # noqa: E402

TEST_SIZE = 100


def classes_in(label_path: Path) -> list[int]:
    if not label_path.exists():
        return []
    return [int(ln.split()[0]) for ln in label_path.read_text().splitlines() if ln.strip()]


def write_yaml(name: str, train_list: Path, extra_train: list[Path] | None = None) -> Path:
    """Write an Ultralytics data yaml that points at the split lists (absolute paths)."""
    trains = [train_list] + (extra_train or [])
    train_field = trains[0].as_posix() if len(trains) == 1 else "[" + ", ".join(t.as_posix() for t in trains) + "]"
    text = (f"# generated by scripts/make_split.py - do not edit\n"
            f"train: {train_field}\n"
            f"val: {(SPLITS / 'val_abs.txt').as_posix()}\n"
            f"test: {(SPLITS / 'test_abs.txt').as_posix()}\n"
            f"names:\n" + "".join(f"  {i}: {n}\n" for i, n in enumerate(CLASS_NAMES)))
    out = SPLITS / name
    out.write_text(text, encoding="utf-8")
    return out


def main():
    rng = random.Random(SEED)
    SPLITS.mkdir(parents=True, exist_ok=True)
    train_imgs = sorted((DATASET / "images" / "train").glob("*"))
    val_imgs = sorted((DATASET / "images" / "val").glob("*"))
    per_img = {p: Counter(classes_in(DATASET / "labels" / "train" / (p.stem + ".txt"))) for p in train_imgs}

    img_count = Counter()
    for c in per_img.values():
        img_count.update(set(c))
    frac = TEST_SIZE / len(train_imgs)
    target = {k: max(2, round(v * frac)) for k, v in img_count.items()}

    remaining = list(train_imgs)
    rng.shuffle(remaining)
    test: list[Path] = []
    have = Counter()
    while len(test) < TEST_SIZE:
        deficit = {k: (target[k] - have[k]) / target[k] for k in target}
        k = max(sorted(deficit), key=lambda c: deficit[c])
        pool = [p for p in remaining if k in per_img[p]] if deficit[k] > 0 else remaining
        pick = pool[0] if pool else remaining[0]
        remaining.remove(pick)
        test.append(pick)
        have.update(set(per_img[pick]))

    test_set = set(test)
    train = [p for p in train_imgs if p not in test_set]
    assert not test_set & set(train) and len(train) + len(test) == len(train_imgs)

    for name, imgs in (("train", train), ("val", val_imgs), ("test", sorted(test))):
        (SPLITS / f"{name}.txt").write_text("\n".join(p.relative_to(ROOT).as_posix() for p in imgs) + "\n")
        (SPLITS / f"{name}_abs.txt").write_text("\n".join(p.as_posix() for p in imgs) + "\n")

    write_yaml("ppe.yaml", SPLITS / "train_abs.txt")

    stats = {"seed": SEED, "train": len(train), "val": len(val_imgs), "test": len(test),
             "test_images_per_class": {CLASS_NAMES[k]: have[k] for k in sorted(have)}}
    (SPLITS / "split_stats.json").write_text(json.dumps(stats, indent=2))
    print(json.dumps(stats, indent=2))
    missing = [CLASS_NAMES[k] for k in range(len(CLASS_NAMES)) if have[k] == 0]
    assert not missing, f"classes missing from test split: {missing}"


if __name__ == "__main__":
    main()
