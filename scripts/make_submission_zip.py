"""Build the submission zip: report, model card, slides, screenshots, SUBMISSION.md and a clean repo copy.

    python scripts/make_submission_zip.py --name <your name>

The repo copy comes from `git archive HEAD` (tracked files only: no datasets, venv, node_modules or
runs/). Research-only checkpoints that the app does not use are left out to keep the zip small; they
stay in the GitHub repository.
"""
from __future__ import annotations

import argparse
import io
import subprocess
import tarfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUB = ROOT / "submission"
SKIP_PREFIX = (
    "models/sitesafe_base_s.onnx",      # YOLO11s comparison, 38 MB
    "models/sitesafe_classical.onnx",   # ablation arms of the synthetic-data experiment
    "models/sitesafe_inpaint.onnx",
    "colab/sitesafe_code.zip",          # regenerated by scripts/make_colab_bundle.py
    "colab/sitesafe_plus_code.zip",
    "models/sitesafe_synth.onnx",       # identical copies are in web/public/models (used by the app)
    "models/sitesafe_plus.onnx",
    "docs/report.docx",                 # identical to Technical_Report.docx / Model_Card.docx at the top of the zip
    "docs/model_card.docx",
)
SKIP_PART = ("/val_batch",)             # Ultralytics sample-batch images; scripts/evaluate.py regenerates them
DOCS = ["Technical_Report.docx", "Model_Card.docx", "SiteSafe_Presentation.pptx", "SUBMISSION.md"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    a = ap.parse_args()
    out = ROOT / f"SiteSafe_Submission_{a.name}.zip"
    tar = subprocess.run(["git", "archive", "--format=tar", "HEAD"], cwd=ROOT, capture_output=True, check=True).stdout
    n_repo = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for d in DOCS:
            z.write(SUB / d, d)
        for f in sorted((SUB / "screenshots").iterdir()):
            z.write(f, f"screenshots/{f.name}")
        for f in sorted((SUB / "figures").iterdir()):
            z.write(f, f"figures/{f.name}")
        with tarfile.open(fileobj=io.BytesIO(tar)) as t:
            for m in t.getmembers():
                if (not m.isfile() or m.name.startswith(SKIP_PREFIX) or m.name.startswith("submission/")
                        or any(part in m.name for part in SKIP_PART)):
                    continue
                z.writestr(f"sitesafe-repo/{m.name}", t.extractfile(m).read())
                n_repo += 1
    print(f"wrote {out.name}: {out.stat().st_size / 1e6:.1f} MB, {n_repo} repo files")


if __name__ == "__main__":
    main()
